// Sesli asistan: duruşma, e-duruşma, masraf ve kişi dosyaları komutları (uydurma föylerle).
import { bosFoy } from "../src/data/foy";
import { sesliKomut } from "../src/data/sesKomut";
let fail = 0;
const ok = (c: boolean, m: string) => { if (!c) { fail++; console.log("✗ " + m); } };
const bugun = "2026-11-09";
const a = bosFoy({ id: "fa", muvekkil: "Deneme Yılmaz", karsiTaraf: "Uydurma A.Ş.", esasNo: "2026/321", durusmalar: [{ id: "d1", tarih: "2026-11-02" }, { id: "d2", tarih: "2026-12-18T10:30" }] });
const b = bosFoy({ id: "fb", muvekkil: "Başka Kişi", karsiTaraf: "Deneme Yılmaz", esasNo: "2025/77" });
const liste = [a, b];
let r = sesliKomut("Yılmaz dosyasında duruşmaya girdik", [a], {}, bugun);
ok(r.baglam.bekleyen?.tip === "durusmaIsle" && (r.baglam.bekleyen as { durusmaId: string }).durusmaId === "d1", "girildi sorusu: " + r.metin);
r = sesliKomut("evet", [a], r.baglam, bugun);
ok(r.eylem?.tip === "durusma" && (r.eylem as { ek: { girildi?: string } }).ek.girildi === "evet", "girildi işlendi");
r = sesliKomut("Yılmaz dosyasında e-duruşma talep ettik", [a], {}, bugun);
ok((r.baglam.bekleyen as { durusmaId?: string; ek?: { e?: string } })?.durusmaId === "d2" && (r.baglam.bekleyen as { ek: { e?: string } }).ek.e === "talep", "e-duruşma talep: " + r.metin);
r = sesliKomut("Yılmaz dosyasında e-duruşma kabul edildi", [a], {}, bugun);
ok((r.baglam.bekleyen as { ek: { e?: string } })?.ek.e === "kabul", "e-duruşma kabul");
r = sesliKomut("Yılmaz dosyasında e-duruşma reddedildi", [a], {}, bugun);
ok((r.baglam.bekleyen as { ek: { e?: string } })?.ek.e === "red", "e-duruşma red");
r = sesliKomut("Yılmaz dosyasına masraf ekle 615 lira harç", [a], {}, bugun);
ok(r.baglam.bekleyen?.tip === "kalemEkle" && (r.baglam.bekleyen as { kalem: { tutar: number; kategori?: string } }).kalem.tutar === 615, "masraf: " + r.metin);
r = sesliKomut("Yılmaz dosyasına tahsilat 20 bin lira", [a], {}, bugun);
ok((r.baglam.bekleyen as { kalem: { tutar: number; tur: string } })?.kalem.tutar === 20000 && (r.baglam.bekleyen as { kalem: { tur: string } }).kalem.tur === "tahsilat", "tahsilat: " + r.metin);
r = sesliKomut("Yılmaz'ın dosyaları", liste, {}, bugun);
ok(/2 dosya/.test(r.metin), "kişinin dosyaları: " + r.metin);
r = sesliKomut("duruşma konuları", [a], {}, bugun);
ok(/duruşma konusu/.test(r.metin), "duruşma konuları: " + r.metin);
r = sesliKomut("tevkil avukatlar ekranını aç", [a], {}, bugun);
ok(r.eylem?.tip === "ekran", "ekran");
if (fail) { console.log(`ses-durusma-test: ${fail} hata`); process.exit(1); } else console.log("ses-durusma-test: tamam");
