-- Üye başına kullanım: dönemdeki oyun sayısı, son etkinlik, Pro ve kredi durumu.
create or replace function public.istat_kullanicilar(p_gun integer default 30)
returns table (kullanici_id uuid, ad_soyad text, eposta text, uyelik timestamptz, oyun bigint, bitti bigint, ucretli bigint,
               son_aktif timestamptz, pro boolean, pro_bitis timestamptz, pro_kaynak text, kredi integer, kariyer_dava bigint, kariyer_puan bigint)
language plpgsql stable security definer set search_path = public as $$
#variable_conflict use_column
declare v_bas timestamptz := now() - make_interval(days => greatest(1, least(coalesce(p_gun, 30), 1100)));
begin
  if not public.yonetici_mi() then raise exception 'Yetki yok'; end if;
  return query
    select p.id, p.ad_soyad, p.eposta, p.olusturma,
      coalesce(u.oyun, 0), coalesce(u.bitti, 0), coalesce(u.ucretli, 0),
      greatest(u.son, kr.son),
      coalesce(a.bitis > now(), false), a.bitis, a.kaynak,
      coalesce(dk.kredi, 0), coalesce(kr.dava, 0), coalesce(kr.puan, 0)
    from public.profiller p
    left join (
      select y.kullanici_id,
        count(y.id) filter (where y.olay = 'dava_basladi' and y.created_at >= v_bas) as oyun,
        count(y.id) filter (where y.olay = 'dava_bitti' and y.created_at >= v_bas) as bitti,
        count(y.id) filter (where y.olay = 'dava_basladi' and y.ucretli and y.created_at >= v_bas) as ucretli,
        max(y.created_at) as son
      from public.kullanim y where y.kullanici_id is not null group by y.kullanici_id
    ) u on u.kullanici_id = p.id
    left join (
      select kk.kullanici_id, count(kk.dava_id) as dava, sum(kk.puan)::bigint as puan, max(kk.guncelleme) as son
      from public.kariyer kk group by kk.kullanici_id
    ) kr on kr.kullanici_id = p.id
    left join public.abonelikler a on a.kullanici_id = p.id
    left join public.derdini_kredi dk on dk.kullanici_id = p.id
    order by greatest(u.son, kr.son) desc nulls last, p.olusturma desc
    limit 5000;
end; $$;
revoke all on function public.istat_kullanicilar(integer) from public, anon;
grant execute on function public.istat_kullanicilar(integer) to authenticated;
