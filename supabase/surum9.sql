-- Bildirimin durumunu ve yanıtını yazar; p_metin verilmişse ve bildiren üye ise gelen kutusuna yanıt mesajı ekler (tek işlem).
-- Dönüş: eklenen mesajın kimliği (mesaj eklenmediyse null).
create or replace function public.hata_yanitla(p_id bigint, p_durum text, p_yanit text, p_baslik text default null, p_metin text default null)
returns uuid
language plpgsql security definer set search_path = public as $$
declare
  h public.hata_bildirimleri;
  v_mesaj uuid;
begin
  if not public.yonetici_mi() then raise exception 'Yetki yok'; end if;
  select hb.id, hb.kullanici_id into h.id, h.kullanici_id from public.hata_bildirimleri hb where hb.id = p_id for update;
  if h.id is null then raise exception 'Bildirim bulunamadı'; end if;
  update public.hata_bildirimleri
     set durum = coalesce(p_durum, durum),
         yanit = coalesce(nullif(trim(p_yanit), ''), yanit),
         yanit_zamani = case when nullif(trim(p_yanit), '') is not null then now() else yanit_zamani end,
         guncelleme = now()
   where id = p_id;
  if nullif(trim(p_metin), '') is not null and h.kullanici_id is not null then
    insert into public.mesajlar (kullanici_id, baslik, metin, tur, ilgili_bildirim, gonderen)
    values (h.kullanici_id, left(coalesce(nullif(trim(p_baslik), ''), 'Hata bildiriminiz'), 160), left(p_metin, 8000), 'yanit', p_id, auth.uid())
    returning id into v_mesaj;
  end if;
  return v_mesaj;
end; $$;
revoke all on function public.hata_yanitla(bigint, text, text, text, text) from public, anon;
grant execute on function public.hata_yanitla(bigint, text, text, text, text) to authenticated;

-- ---------- yönetici: istatistikler ----------
-- Dönemler İstanbul saatine göre. "Aktif" = o dönemde en az bir olay yazan kişi (üye kimliği, misafirde cihaz kimliği).
-- Pro abone sayısı yaklaşıktır: abonelik geçmişi tutulmadığı için dönem sonunda bitişi gelmemiş ve ilk ödemesi
-- (yoksa son güncellemesi) o tarihten önce olan satırlar sayılır.

create or replace function public.istat_seri(p_birim text default 'gun', p_adet integer default 30)
returns table (donem date, oyun_ucretsiz bigint, oyun_ucretli bigint, bitti bigint, kazanilan bigint, birakilan bigint,
               aktif bigint, yeni_uye bigint, pro bigint, odeme bigint, odeme_test bigint, gelir numeric, paywall bigint, danisma bigint)
language plpgsql stable security definer set search_path = public as $$
#variable_conflict use_column
declare
  v_ay boolean := p_birim = 'ay';
  v_b text := case when p_birim = 'ay' then 'month' else 'day' end;
  v_adim interval := case when p_birim = 'ay' then interval '1 month' else interval '1 day' end;
  v_n integer := greatest(1, least(coalesce(p_adet, 30), case when p_birim = 'ay' then 36 else 400 end));
  v_bugun date := date_trunc(case when p_birim = 'ay' then 'month' else 'day' end, now() at time zone 'Europe/Istanbul')::date;
  v_bas date;
  v_bas_t timestamptz;
begin
  if not public.yonetici_mi() then raise exception 'Yetki yok'; end if;
  v_bas := case when v_ay then (v_bugun - make_interval(months => v_n - 1))::date else v_bugun - (v_n - 1) end;
  v_bas_t := v_bas::timestamp at time zone 'Europe/Istanbul';
  return query
  with d as (
    select g::date as donem, least((g + v_adim) at time zone 'Europe/Istanbul', now()) as son
    from generate_series(v_bas::timestamp, v_bugun::timestamp, v_adim) g
  ),
  k as (
    select date_trunc(v_b, x.created_at at time zone 'Europe/Istanbul')::date as donem,
      count(x.id) filter (where x.olay = 'dava_basladi' and not x.ucretli) as oyun_ucretsiz,
      count(x.id) filter (where x.olay = 'dava_basladi' and x.ucretli) as oyun_ucretli,
      count(x.id) filter (where x.olay = 'dava_bitti') as bitti,
      count(x.id) filter (where x.olay = 'dava_bitti' and x.kazandi) as kazanilan,
      count(x.id) filter (where x.olay = 'dava_birakti') as birakilan,
      count(distinct coalesce(x.kullanici_id::text, x.oturum)) as aktif,
      count(x.id) filter (where x.olay = 'paywall_goruldu') as paywall,
      count(x.id) filter (where x.olay = 'danisma') as danisma
    from public.kullanim x where x.created_at >= v_bas_t group by 1
  ),
  u as (
    select date_trunc(v_b, p.olusturma at time zone 'Europe/Istanbul')::date as donem, count(p.id) as yeni_uye
    from public.profiller p where p.olusturma >= v_bas_t group by 1
  ),
  o as (
    select date_trunc(v_b, z.zaman at time zone 'Europe/Istanbul')::date as donem,
      count(z.olay_id) filter (where coalesce(z.ortam, '') <> 'SANDBOX' and z.tur in ('INITIAL_PURCHASE', 'RENEWAL', 'NON_RENEWING_PURCHASE', 'PRODUCT_CHANGE')) as odeme,
      count(z.olay_id) filter (where z.ortam = 'SANDBOX' and z.tur in ('INITIAL_PURCHASE', 'RENEWAL', 'NON_RENEWING_PURCHASE', 'PRODUCT_CHANGE')) as odeme_test,
      coalesce(sum(case when coalesce(z.ortam, '') <> 'SANDBOX' and jsonb_typeof(z.ham -> 'price') = 'number' then (z.ham ->> 'price')::numeric end), 0) as gelir
    from public.odeme_olaylari z where z.zaman >= v_bas_t group by 1
  ),
  ilk as (
    select a.kullanici_id, a.bitis,
      coalesce((select min(oo.zaman) from public.odeme_olaylari oo where oo.kullanici_id = a.kullanici_id), a.guncelleme) as basla
    from public.abonelikler a
  ),
  pr as (
    select d.donem, count(i.kullanici_id) as pro from d join ilk i on i.bitis >= d.son and i.basla <= d.son group by d.donem
  )
  select d.donem,
    coalesce(k.oyun_ucretsiz, 0), coalesce(k.oyun_ucretli, 0), coalesce(k.bitti, 0), coalesce(k.kazanilan, 0), coalesce(k.birakilan, 0),
    coalesce(k.aktif, 0), coalesce(u.yeni_uye, 0), coalesce(pr.pro, 0), coalesce(o.odeme, 0), coalesce(o.odeme_test, 0), coalesce(o.gelir, 0),
    coalesce(k.paywall, 0), coalesce(k.danisma, 0)
  from d
  left join k on k.donem = d.donem
  left join u on u.donem = d.donem
  left join o on o.donem = d.donem
  left join pr on pr.donem = d.donem
  order by d.donem;
end; $$;
revoke all on function public.istat_seri(text, integer) from public, anon;
grant execute on function public.istat_seri(text, integer) to authenticated;

-- Seçilen dönemin özeti (gün sayısı): kutucuklardaki toplamlar.
create or replace function public.istat_ozet(p_gun integer default 30) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare
  v_bas timestamptz := now() - make_interval(days => greatest(1, least(coalesce(p_gun, 30), 1100)));
  r jsonb;
begin
  if not public.yonetici_mi() then raise exception 'Yetki yok'; end if;
  select jsonb_build_object(
    'uye', (select count(id) from public.profiller),
    'yeni_uye', (select count(id) from public.profiller where olusturma >= v_bas),
    'pro_aktif', (select count(kullanici_id) from public.abonelikler where bitis > now()),
    'pro_kaynak', coalesce((select jsonb_object_agg(kaynak, n) from (select kaynak, count(kullanici_id) as n from public.abonelikler where bitis > now() group by kaynak) s), '{}'::jsonb),
    'kredi_toplam', coalesce((select sum(kredi) from public.derdini_kredi), 0),
    'aktif', (select count(distinct coalesce(kullanici_id::text, oturum)) from public.kullanim where created_at >= v_bas),
    'aktif_uye', (select count(distinct kullanici_id) from public.kullanim where created_at >= v_bas),
    'misafir', (select count(distinct oturum) from public.kullanim where created_at >= v_bas and kullanici_id is null),
    'oyun', (select count(id) from public.kullanim where created_at >= v_bas and olay = 'dava_basladi'),
    'oyun_ucretli', (select count(id) from public.kullanim where created_at >= v_bas and olay = 'dava_basladi' and ucretli),
    'bitti', (select count(id) from public.kullanim where created_at >= v_bas and olay = 'dava_bitti'),
    'kazanilan', (select count(id) from public.kullanim where created_at >= v_bas and olay = 'dava_bitti' and kazandi),
    'paywall', (select count(id) from public.kullanim where created_at >= v_bas and olay = 'paywall_goruldu'),
    'satin_alma', (select count(id) from public.kullanim where created_at >= v_bas and olay = 'satin_alma'),
    'danisma', (select count(id) from public.kullanim where created_at >= v_bas and olay = 'danisma'),
    'odeme', (select count(olay_id) from public.odeme_olaylari where zaman >= v_bas and coalesce(ortam, '') <> 'SANDBOX'
                and tur in ('INITIAL_PURCHASE', 'RENEWAL', 'NON_RENEWING_PURCHASE', 'PRODUCT_CHANGE')),
    'gelir', coalesce((select sum((ham ->> 'price')::numeric) from public.odeme_olaylari
                where zaman >= v_bas and coalesce(ortam, '') <> 'SANDBOX' and jsonb_typeof(ham -> 'price') = 'number'), 0),
    'hata_acik', (select count(id) from public.hata_bildirimleri where durum in ('yeni', 'inceleniyor'))
  ) into r;
  return r;
end; $$;
revoke all on function public.istat_ozet(integer) from public, anon;
grant execute on function public.istat_ozet(integer) to authenticated;

-- En çok oynanan davalar.
create or replace function public.istat_davalar(p_gun integer default 30, p_sinir integer default 20)
returns table (dava_id text, oyun bigint, bitti bigint, kazanilan bigint, ort_puan numeric, kisi bigint, ucretli boolean)
language plpgsql stable security definer set search_path = public as $$
#variable_conflict use_column
declare v_bas timestamptz := now() - make_interval(days => greatest(1, least(coalesce(p_gun, 30), 1100)));
begin
  if not public.yonetici_mi() then raise exception 'Yetki yok'; end if;
  return query
    select x.dava_id,
      count(x.id) filter (where x.olay = 'dava_basladi'),
      count(x.id) filter (where x.olay = 'dava_bitti'),
      count(x.id) filter (where x.olay = 'dava_bitti' and x.kazandi),
      round(avg(x.puan) filter (where x.olay = 'dava_bitti'), 1),
      count(distinct coalesce(x.kullanici_id::text, x.oturum)),
      bool_or(x.ucretli)
    from public.kullanim x
    where x.created_at >= v_bas and x.dava_id is not null and x.olay in ('dava_basladi', 'dava_bitti')
    group by x.dava_id
    order by 2 desc, 3 desc limit greatest(1, least(coalesce(p_sinir, 20), 200));
end; $$;
revoke all on function public.istat_davalar(integer, integer) from public, anon;
grant execute on function public.istat_davalar(integer, integer) to authenticated;

