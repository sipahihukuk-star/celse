-- Celse · 9. kurulum: kullanım istatistikleri, gelen kutusu (duyuru ve yanıtlar) ve hata bildirimleri.
-- - kullanim: hafif olay kaydı (dava başladı / bitti / bırakıldı, danışma, Pro ekranı görüldü, satın alma).
--   Herkes (misafir de) ekler; yalnız yönetici okur. Hesap silinince satırlar kimliksiz kalır (takma adlı cihaz kimliği).
-- - istat_...(): yönetim panelindeki "İstatistikler" bölümünün özet işlevleri; yalnız yönetici çalıştırabilir.
-- - hata_bildirimleri: oyuncunun duruşma ekranından gönderdiği hata bildirimleri. Herkes ekler, kendi bildirimini görür;
--   yönetici okur, durumunu değiştirir ve yanıtlar.
-- - mesajlar ve mesaj_okundu: gelen kutusu. kullanici_id boşsa bütün oyunculara duyurudur. Yalnız yönetici yazar.
-- Supabase > SQL Editor'de bir kez çalıştırılır (schema, yonetim ve surum3 ile surum7 arasındaki kurulumlardan sonra).
-- Tekrar çalıştırmak zararsızdır.

-- ---------- kullanım olayları ----------
create table if not exists public.kullanim (
  id bigint generated by default as identity primary key,
  kullanici_id uuid references auth.users (id) on delete set null,
  oturum text not null check (char_length(oturum) between 8 and 64),
  olay text not null,
  dava_id text check (char_length(dava_id) <= 80),
  mod text,
  ucretli boolean not null default false,
  puan smallint check (puan between 0 and 100),
  kazandi boolean,
  platform text check (platform in ('ios', 'android', 'web', 'diger')),
  surum text check (char_length(surum) <= 40),
  created_at timestamptz not null default now()
);
alter table public.kullanim drop constraint if exists kullanim_olay_check;
alter table public.kullanim add constraint kullanim_olay_check
  check (olay in ('dava_basladi', 'dava_bitti', 'dava_birakti', 'danisma', 'paywall_goruldu', 'satin_alma'));
alter table public.kullanim drop constraint if exists kullanim_mod_check;
alter table public.kullanim add constraint kullanim_mod_check
  check (mod is null or mod in ('solo', 'duel', 'tahkim', 'antrenman', 'kariyer'));
create index if not exists kullanim_zaman on public.kullanim (created_at);
create index if not exists kullanim_oturum on public.kullanim (oturum, created_at);
create index if not exists kullanim_kullanici on public.kullanim (kullanici_id, created_at);

-- Kaba sınır: bir cihaz kimliği 10 dakikada en çok 300 olay yazabilir.
create or replace function public.kullanim_sinir_ok(p_oturum text) returns boolean
language sql stable security definer set search_path = public as $$
  select count(id) < 300 from public.kullanim where oturum = p_oturum and created_at > now() - interval '10 minutes';
$$;
revoke all on function public.kullanim_sinir_ok(text) from public;
grant execute on function public.kullanim_sinir_ok(text) to anon, authenticated;

alter table public.kullanim enable row level security;
drop policy if exists "kullanım olayı ekler" on public.kullanim;
create policy "kullanım olayı ekler" on public.kullanim for insert to anon, authenticated
  with check (
    (kullanici_id is null or kullanici_id = auth.uid())
    and created_at between now() - interval '10 minutes' and now() + interval '1 minute'
    and public.kullanim_sinir_ok(oturum)
  );
drop policy if exists "yönetici kullanımı görür" on public.kullanim;
create policy "yönetici kullanımı görür" on public.kullanim for select using (public.yonetici_mi());
grant insert on public.kullanim to anon, authenticated;
grant select on public.kullanim to authenticated;

-- ---------- hata bildirimleri ----------
create table if not exists public.hata_bildirimleri (
  id bigint generated by default as identity primary key,
  kullanici_id uuid references auth.users (id) on delete set null,
  dava_id text check (char_length(dava_id) <= 80),
  adim integer,
  baglam jsonb not null default '{}'::jsonb,
  kategori text not null check (kategori in ('metin', 'hukuki', 'gorsel', 'teknik', 'diger')),
  aciklama text not null check (char_length(aciklama) between 3 and 4000),
  durum text not null default 'yeni' check (durum in ('yeni', 'inceleniyor', 'duzeltildi', 'reddedildi')),
  yanit text check (char_length(yanit) <= 4000),
  yanit_zamani timestamptz,
  guncelleme timestamptz not null default now(),
  created_at timestamptz not null default now()
);
alter table public.hata_bildirimleri drop constraint if exists hata_baglam_boyut;
alter table public.hata_bildirimleri add constraint hata_baglam_boyut check (pg_column_size(baglam) <= 8000);
create index if not exists hata_bildirimleri_durum on public.hata_bildirimleri (durum, created_at desc);
create index if not exists hata_bildirimleri_kullanici on public.hata_bildirimleri (kullanici_id, created_at desc);

-- Kaba sınır: üye 10 dakikada en çok 10, misafirler toplam 10 dakikada en çok 60 bildirim gönderebilir.
create or replace function public.hata_sinir_ok() returns boolean
language sql stable security definer set search_path = public as $$
  select case when auth.uid() is null
    then (select count(id) < 60 from public.hata_bildirimleri where kullanici_id is null and created_at > now() - interval '10 minutes')
    else (select count(id) < 10 from public.hata_bildirimleri where kullanici_id = auth.uid() and created_at > now() - interval '10 minutes')
  end;
$$;
revoke all on function public.hata_sinir_ok() from public;
grant execute on function public.hata_sinir_ok() to anon, authenticated;

alter table public.hata_bildirimleri enable row level security;
drop policy if exists "hata bildirir" on public.hata_bildirimleri;
create policy "hata bildirir" on public.hata_bildirimleri for insert to anon, authenticated
  with check (
    (kullanici_id is null or kullanici_id = auth.uid())
    and durum = 'yeni' and yanit is null and yanit_zamani is null
    and created_at between now() - interval '10 minutes' and now() + interval '1 minute'
    and public.hata_sinir_ok()
  );
drop policy if exists "kendi bildirimini görür" on public.hata_bildirimleri;
create policy "kendi bildirimini görür" on public.hata_bildirimleri for select using (auth.uid() = kullanici_id or public.yonetici_mi());
drop policy if exists "yönetici bildirimi günceller" on public.hata_bildirimleri;
create policy "yönetici bildirimi günceller" on public.hata_bildirimleri for update using (public.yonetici_mi()) with check (public.yonetici_mi());
drop policy if exists "yönetici bildirimi siler" on public.hata_bildirimleri;
create policy "yönetici bildirimi siler" on public.hata_bildirimleri for delete using (public.yonetici_mi());
grant insert on public.hata_bildirimleri to anon, authenticated;
grant select, update, delete on public.hata_bildirimleri to authenticated;

-- ---------- gelen kutusu ----------
create table if not exists public.mesajlar (
  id uuid primary key default gen_random_uuid(),
  kullanici_id uuid references auth.users (id) on delete cascade,
  baslik text not null check (char_length(baslik) between 1 and 160),
  metin text not null check (char_length(metin) between 1 and 8000),
  tur text not null default 'duyuru' check (tur in ('duyuru', 'yanit', 'sistem')),
  ilgili_bildirim bigint references public.hata_bildirimleri (id) on delete set null,
  gonderen uuid references auth.users (id) on delete set null,
  created_at timestamptz not null default now()
);
create index if not exists mesajlar_kullanici on public.mesajlar (kullanici_id, created_at desc);

create table if not exists public.mesaj_okundu (
  kullanici_id uuid not null references auth.users (id) on delete cascade,
  mesaj_id uuid not null references public.mesajlar (id) on delete cascade,
  zaman timestamptz not null default now(),
  primary key (kullanici_id, mesaj_id)
);

alter table public.mesajlar enable row level security;
drop policy if exists "kendi mesajlarını ve duyuruları görür" on public.mesajlar;
create policy "kendi mesajlarını ve duyuruları görür" on public.mesajlar for select
  using (kullanici_id is null or kullanici_id = auth.uid() or public.yonetici_mi());
drop policy if exists "yönetici mesaj yazar" on public.mesajlar;
create policy "yönetici mesaj yazar" on public.mesajlar for insert to authenticated with check (public.yonetici_mi());
drop policy if exists "yönetici mesaj düzeltir" on public.mesajlar;
create policy "yönetici mesaj düzeltir" on public.mesajlar for update using (public.yonetici_mi()) with check (public.yonetici_mi());
drop policy if exists "yönetici mesaj siler" on public.mesajlar;
create policy "yönetici mesaj siler" on public.mesajlar for delete using (public.yonetici_mi());
grant select on public.mesajlar to anon, authenticated;
grant insert, update, delete on public.mesajlar to authenticated;

alter table public.mesaj_okundu enable row level security;
drop policy if exists "kendi okuduklarını görür" on public.mesaj_okundu;
create policy "kendi okuduklarını görür" on public.mesaj_okundu for select using (auth.uid() = kullanici_id or public.yonetici_mi());
drop policy if exists "kendi mesajını okundu yapar" on public.mesaj_okundu;
create policy "kendi mesajını okundu yapar" on public.mesaj_okundu for insert to authenticated
  with check (
    auth.uid() = kullanici_id
    and exists (select 1 from public.mesajlar m where m.id = mesaj_id and (m.kullanici_id is null or m.kullanici_id = auth.uid()))
  );
grant select, insert on public.mesaj_okundu to authenticated;

-- Oyuncu açtığı mesajları okundu yapar (yalnız kendi mesajları ve duyurular; tekrar güvenli).
create or replace function public.mesajlari_okundu(p_ids uuid[]) returns integer
language plpgsql security definer set search_path = public as $$
declare n integer;
begin
  if auth.uid() is null then return 0; end if;
  insert into public.mesaj_okundu (kullanici_id, mesaj_id)
  select auth.uid(), m.id from public.mesajlar m
  where m.id = any(p_ids) and (m.kullanici_id is null or m.kullanici_id = auth.uid())
  on conflict do nothing;
  get diagnostics n = row_count;
  return n;
end; $$;
revoke all on function public.mesajlari_okundu(uuid[]) from public, anon;
grant execute on function public.mesajlari_okundu(uuid[]) to authenticated;

-- ---------- yönetici: kişi arama, gönderilen mesajlar, hata bildirimleri ----------
create or replace function public.yonetici_kullanici_ara(p_q text)
returns table (id uuid, ad_soyad text, eposta text)
language plpgsql stable security definer set search_path = public as $$
#variable_conflict use_column
begin
  if not public.yonetici_mi() then raise exception 'Yetki yok'; end if;
  return query
    select p.id, p.ad_soyad, p.eposta from public.profiller p
    where char_length(trim(coalesce(p_q, ''))) >= 2
      and (p.ad_soyad ilike '%' || trim(p_q) || '%' or p.eposta ilike '%' || trim(p_q) || '%')
    order by p.ad_soyad limit 20;
end; $$;
revoke all on function public.yonetici_kullanici_ara(text) from public, anon;
grant execute on function public.yonetici_kullanici_ara(text) to authenticated;

create or replace function public.yonetici_mesajlar(p_sinir integer default 100)
returns table (id uuid, kullanici_id uuid, ad_soyad text, eposta text, baslik text, metin text, tur text, ilgili_bildirim bigint, created_at timestamptz, okuyan bigint)
language plpgsql stable security definer set search_path = public as $$
#variable_conflict use_column
begin
  if not public.yonetici_mi() then raise exception 'Yetki yok'; end if;
  return query
    select m.id, m.kullanici_id, p.ad_soyad, p.eposta, m.baslik, m.metin, m.tur, m.ilgili_bildirim, m.created_at,
           (select count(o.mesaj_id) from public.mesaj_okundu o where o.mesaj_id = m.id)
    from public.mesajlar m left join public.profiller p on p.id = m.kullanici_id
    order by m.created_at desc limit greatest(1, least(coalesce(p_sinir, 100), 500));
end; $$;
revoke all on function public.yonetici_mesajlar(integer) from public, anon;
grant execute on function public.yonetici_mesajlar(integer) to authenticated;

create or replace function public.yonetici_hata_listesi(p_durum text default null, p_sinir integer default 200)
returns table (id bigint, kullanici_id uuid, ad_soyad text, eposta text, dava_id text, adim integer, baglam jsonb, kategori text,
               aciklama text, durum text, yanit text, yanit_zamani timestamptz, created_at timestamptz)
